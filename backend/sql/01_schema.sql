-- Esquema v2. Ejecutar en una base NUEVA: no migra ni borra la base anterior.
BEGIN;
CREATE TABLE fuente (
 id text PRIMARY KEY, source_type text NOT NULL CHECK(source_type IN ('dataset','caso_real','sistema','sintetico')),
 source_file text NOT NULL, source_hash text NOT NULL CHECK(length(source_hash)=64),
 actualizado timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE lote_importacion (
 id text PRIMARY KEY, manifiesto jsonb NOT NULL, creado timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE registro_fuente (
 canonical_id text PRIMARY KEY, fuente_id text NOT NULL REFERENCES fuente(id),
 source_record_id text NOT NULL, source_hash text NOT NULL CHECK(length(source_hash)=64),
 lote_id text NOT NULL REFERENCES lote_importacion(id), datos jsonb NOT NULL,
 actualizado timestamptz NOT NULL DEFAULT now(), presente boolean NOT NULL DEFAULT true, UNIQUE(fuente_id,source_record_id)
);
CREATE TABLE error_calidad_datos (
 id text PRIMARY KEY, lote_id text NOT NULL REFERENCES lote_importacion(id),
 fuente_id text REFERENCES fuente(id), registro_id text, codigo text NOT NULL,
 detalle text NOT NULL, creado timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE registro_revision (
 canonical_id text NOT NULL REFERENCES registro_fuente(canonical_id), source_hash text NOT NULL,
 lote_id text NOT NULL REFERENCES lote_importacion(id), datos jsonb NOT NULL,
 creado timestamptz NOT NULL DEFAULT now(), PRIMARY KEY(canonical_id,source_hash)
);
CREATE TABLE eps (
 id varchar(80) PRIMARY KEY REFERENCES registro_fuente(canonical_id), nombre text NOT NULL,
 region text, tamano text, simulado boolean NOT NULL DEFAULT false
);
CREATE TABLE usuario (
 id varchar(80) PRIMARY KEY, nombre_visible text NOT NULL,
 perfil text NOT NULL CHECK(perfil IN ('sunass','eps')), eps_id varchar(80) REFERENCES eps(id),
 activo boolean NOT NULL DEFAULT true, password_hash text,
 CHECK((perfil='eps' AND eps_id IS NOT NULL) OR (perfil='sunass' AND eps_id IS NULL))
);
CREATE TABLE proyecto_inversion (
 eps_id varchar(80) NOT NULL REFERENCES eps(id), cod_proyecto text NOT NULL,
 PRIMARY KEY(eps_id,cod_proyecto)
);
CREATE TABLE tramite (
 id varchar(80) PRIMARY KEY REFERENCES registro_fuente(canonical_id), procedimiento text NOT NULL,
 eps_id varchar(80) NOT NULL REFERENCES eps(id), titulo text NOT NULL,
 estado text NOT NULL CHECK(estado IN ('en_evaluacion','requiere_respuesta','requiere_subsanacion','en_consulta','autorizado','no_autorizado','concluido')),
 paso_actual integer NOT NULL DEFAULT 1 CHECK(paso_actual>0), etapa text NOT NULL,
 responsable text, fecha_inicio date, fecha_inicio_etapa date, fecha_fin date,
 publicable boolean NOT NULL DEFAULT false, simulado boolean NOT NULL DEFAULT false,
 version integer NOT NULL DEFAULT 1, huella_fuentes text NOT NULL DEFAULT '',
 presentacion json, ficha_eps json, ficha_agente json,
 actualizado timestamptz NOT NULL DEFAULT now(), UNIQUE(id,eps_id),
 CHECK(fecha_fin IS NULL OR fecha_inicio IS NULL OR fecha_fin>=fecha_inicio)
);
CREATE TABLE documento (
 id varchar(120) PRIMARY KEY REFERENCES registro_fuente(canonical_id), tramite_id varchar(80) NOT NULL REFERENCES tramite(id),
 titulo text NOT NULL, referencia text, visibilidad text NOT NULL DEFAULT 'interna' CHECK(visibilidad IN ('interna','partes','publica')),
 estado_validacion text NOT NULL DEFAULT 'por_validar', archivo text, paginas integer CHECK(paginas>0),
 simulado boolean NOT NULL DEFAULT false, UNIQUE(id,tramite_id)
);
CREATE TABLE fragmento (
 id varchar(140) PRIMARY KEY, documento_id varchar(120) NOT NULL, tramite_id varchar(80) NOT NULL,
 pagina_pdf integer NOT NULL CHECK(pagina_pdf>0), pagina_impresa text, texto text NOT NULL,
 requiere_ocr boolean NOT NULL DEFAULT false, metadatos json,
 FOREIGN KEY(documento_id,tramite_id) REFERENCES documento(id,tramite_id), UNIQUE(documento_id,pagina_pdf)
);
CREATE TABLE metadato_documental (
 documento_id varchar(120) PRIMARY KEY REFERENCES documento(id), numero_candidato text,
 fecha_candidata date, actor_candidato text, etapa_carpeta text,
 validado boolean NOT NULL DEFAULT false, metodo text NOT NULL
);
CREATE TABLE vinculo_documental (
 origen_id varchar(120) NOT NULL REFERENCES documento(id), destino_id varchar(120) NOT NULL REFERENCES documento(id),
 tipo text NOT NULL, fuente_fragmento varchar(140) REFERENCES fragmento(id),
 validado boolean NOT NULL DEFAULT false, PRIMARY KEY(origen_id,destino_id,tipo), CHECK(origen_id<>destino_id)
);
CREATE TABLE actuacion (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tramite_id varchar(80) NOT NULL REFERENCES tramite(id),
 tipo text NOT NULL, titulo text NOT NULL, detalle text, fecha_acreditada date, fecha_por_validar boolean NOT NULL DEFAULT false,
 actor text, documento_id varchar(120), fuente text, usuario_id varchar(80) REFERENCES usuario(id),
 estado_origen text NOT NULL, estado_destino text NOT NULL, paso_origen integer NOT NULL, paso_destino integer NOT NULL,
 verificada boolean NOT NULL DEFAULT true, clave_idempotencia text, peticion_hash varchar(64), registrado timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(documento_id,tramite_id) REFERENCES documento(id,tramite_id), UNIQUE(tramite_id,clave_idempotencia)
);
CREATE TABLE regla_plazo (
 id text PRIMARY KEY, procedimiento text NOT NULL, etapa text, evento_inicial text NOT NULL,
 dias integer NOT NULL CHECK(dias>0), calendario text NOT NULL DEFAULT 'habiles', fuente text NOT NULL,
 validada boolean NOT NULL DEFAULT false, motivo_pendiente text
);
CREATE TABLE plazo (
 id text PRIMARY KEY, tramite_id varchar(80) NOT NULL REFERENCES tramite(id),
 tipo text NOT NULL CHECK(tipo IN ('normativo','gestion','oficio')),
 fuente_id text NOT NULL REFERENCES fuente(id), documento_id varchar(120), regla text NOT NULL,
 evento_inicial text, fecha_inicio date, fecha_fin date, fecha_notificacion date, dias integer CHECK(dias>0),
 validado boolean NOT NULL DEFAULT false, motivo text, etapa text,
 FOREIGN KEY(documento_id,tramite_id) REFERENCES documento(id,tramite_id)
);
CREATE TABLE suspension (
 id text PRIMARY KEY, plazo_id text NOT NULL REFERENCES plazo(id), documento_id varchar(120) NOT NULL REFERENCES documento(id),
 inicio date NOT NULL, fin date NOT NULL CHECK(fin>=inicio), validada boolean NOT NULL DEFAULT false
);
CREATE TABLE prorroga (
 id text PRIMARY KEY, plazo_id text NOT NULL REFERENCES plazo(id), documento_id varchar(120) NOT NULL REFERENCES documento(id),
 fecha_notificacion date NOT NULL, dias integer NOT NULL CHECK(dias>0), validada boolean NOT NULL DEFAULT false
);
CREATE TABLE calendario_dia (
 fecha date PRIMARY KEY, laborable boolean NOT NULL, validado boolean NOT NULL DEFAULT false,
 fuente_id text NOT NULL REFERENCES fuente(id)
);
CREATE TABLE publicacion (
 id text PRIMARY KEY, tramite_id varchar(80) NOT NULL UNIQUE REFERENCES tramite(id), resumen json NOT NULL,
 ficha json, publicada boolean NOT NULL DEFAULT false
);
CREATE TABLE documento_recibido (id text PRIMARY KEY, datos json NOT NULL, incorporado_a varchar(80) REFERENCES tramite(id));
CREATE TABLE alerta (id text PRIMARY KEY, tramite_id varchar(80) REFERENCES tramite(id), datos json NOT NULL, atendida boolean NOT NULL DEFAULT false);
CREATE TABLE cifra_sector (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, datos json NOT NULL);
CREATE TABLE conversacion (
 id text PRIMARY KEY, usuario_id varchar(80) REFERENCES usuario(id), ambito text NOT NULL,
 eps_id varchar(80) REFERENCES eps(id), visitante_id varchar(36), tramite_id varchar(80) NOT NULL REFERENCES tramite(id), creada timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE mensaje (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, conversacion_id text NOT NULL REFERENCES conversacion(id) ON DELETE CASCADE,
 pregunta text NOT NULL, respuesta text NOT NULL, estado text NOT NULL, fuentes json, advertencias json, modelo text,
 duracion_ms integer, desde_cache boolean NOT NULL DEFAULT false, creado timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE respuesta_cache (clave text PRIMARY KEY, tramite_id varchar(80) NOT NULL REFERENCES tramite(id), salida json NOT NULL, guardado timestamptz NOT NULL DEFAULT now());
COMMIT;
