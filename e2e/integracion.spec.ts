import { test, expect, type Page, type BrowserContext } from '@playwright/test'
import fs from 'node:fs'
const path = process.env.QA_ACCOUNTS_JSON
test.skip(!path || !process.env.QA_SCENARIO_FILE || !process.env.QA_TEST_PDF, 'Requiere QA local aislado y cuentas por archivo privado; no ejecutar contra producción.')
const state = path ? JSON.parse(fs.readFileSync(path, 'utf8')) : { accounts: [] }
const scenario = process.env.QA_SCENARIO_FILE ? JSON.parse(fs.readFileSync(process.env.QA_SCENARIO_FILE, 'utf8')) : {}
const base = process.env.QA_BASE_URL ?? 'https://localhost:5444'
if (!['localhost', '127.0.0.1'].includes(new URL(base).hostname)) throw new Error('Las pruebas con escrituras requieren un QA local aislado')

async function protect(context: BrowserContext) {
  context.setDefaultTimeout(15_000)
  await context.route('**/*', (route) => {
    const url = new URL(route.request().url())
    if (!['localhost', '127.0.0.1'].includes(url.hostname) || /\/api\/(agente|publico\/asistente)\/chat/.test(url.pathname)) return route.abort('blockedbyclient')
    return route.continue()
  })
}
async function login(page: Page, role: string) {
  const user = state.accounts.find((a: { role: string }) => a.role === role)
  await page.goto(base + '/api/auth/login')
  await page.locator('#username').fill(user.id)
  await page.locator('#password').fill(user.password)
  await page.locator('#kc-login').click()
  await expect(page).toHaveURL(/\/(sunass|eps)\//)
}
async function width(page: Page) {
  const sizes = await page.evaluate(() => ({ body: document.documentElement.scrollWidth, viewport: window.innerWidth }))
  expect(sizes.body, `Sin desbordamiento horizontal en ${new URL(page.url()).pathname}`).toBeLessThanOrEqual((page.viewportSize()?.width ?? sizes.viewport) + 2)
}
