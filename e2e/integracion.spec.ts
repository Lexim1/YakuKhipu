test('vistas operativas y exportación a 320 px', async ({ browser }, info) => {
  const context = await browser.newContext({ ...info.project.use, viewport: { width: 320, height: 800 }, ignoreHTTPSErrors: true })
  await protect(context)
  const page = await context.newPage()
  const failures: string[] = []
  page.on('pageerror', (e) => failures.push(e.message))
  page.on('response', (r) => { if (r.status() >= 500) failures.push(`${r.status()} ${new URL(r.url()).pathname}`) })
  await login(page, 'coordinacion_dre')
  for (const route of ['dashboard', 'ficha-eps', 'actos', 'encargos', 'reportes', 'expedientes', 'alertas', 'te-toca', 'recepcion']) {
    await page.goto(base + '/sunass/' + route)
    await page.waitForLoadState('networkidle')
    await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
    await width(page)
  }
  await page.goto(base + '/sunass/reportes')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Descargar CSV de mi ámbito' }).click()
  const stream = await (await download).createReadStream()
  const chunks = []; for await (const chunk of stream!) chunks.push(chunk)
  expect(Buffer.concat(chunks).toString('utf8')).toContain('ejecucion_reportada_soles')
  await page.goto(base + '/sunass/dashboard'); await page.waitForLoadState('networkidle')
  const logo = page.locator('img[src="/logo.png"]').first()
  expect(await logo.evaluate((img: HTMLImageElement) => img.complete && img.naturalWidth > 0)).toBe(true)
  await page.screenshot({ path: `${process.env.QA_SCREENSHOTS ?? '../private'}/qa-320-${info.project.name}.png`, scale: 'css', animations: 'disabled' })
  expect(failures).toEqual([])
  await context.close()
})
